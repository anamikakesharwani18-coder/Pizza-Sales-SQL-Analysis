/*
PROJECT: PIZZA SALES ANALYSIS
DATABASE: PostgreSQL
TOOL: pgAdmin

OBJECTIVE:
To analyse pizza sales data and identify
business insights related to orders,
revenue, product performance and sales trends.

TABLES:
1. orders
2. order_details
3. pizzas
4. pizza_types
*/


--total number of orders:
SELECT COUNT(*) FROM orders;

--total pizzas sold:
SELECT SUM(quantity) FROM order_details;

--unique pizza_types:
SELECT DISTINCT(name) FROM pizza_types;
SELECT COUNT(DISTINCT name) FROM pizza_types;

--most expensive pizza:
SELECT MAX(price) FROM pizzas;
SELECT t.name, MAX(p.price) AS max_price 
FROM pizzas p
JOIN pizza_types t ON p.pizza_type_id = t.pizza_type_id
GROUP BY t.name
ORDER BY max_price DESC limit 1;

--best selling pizza category:
SELECT t.category, SUM(d.quantity)
FROM order_details d
JOIN pizzas p ON d.pizza_id = p.pizza_id
JOIN pizza_types t ON t.pizza_type_id = p.pizza_type_id
GROUP BY t.category
ORDER BY SUM(d.quantity) DESC LIMIT 1;

-- top 5 best selling pizza types:
SELECT t.name, SUM(d.quantity)
FROM order_details d
JOIN pizzas p ON d.pizza_id = p.pizza_id
JOIN pizza_types t ON t.pizza_type_id = p.pizza_type_id
GROUP BY t.name
ORDER BY SUM (d.quantity) DESC LIMIT 5;

--what is the total revenue generated by each pizza category:
SELECT t.category, SUM(d.quantity*p.price) AS revenue
FROM order_details d
JOIN pizzas p ON p.pizza_id = d.pizza_id
JOIN pizza_types t ON p.pizza_type_id = t.pizza_type_id
GROUP BY t.category;

--what is the total revenue generated by each pizza size:
SELECT p.size, SUM(d.quantity*p.price) AS size_revenue
FROM order_details d
JOIN pizzas p ON p.pizza_id = d.pizza_id
GROUP BY p.size;

--how many orders were placed on each day:
SELECT date, COUNT(order_id)
FROM orders
GROUP BY date;

--how many pizzas were sold on each day:
SELECT o.date, COUNT(d.quantity) AS orders_placed
FROM order_details d
JOIN orders o ON o.order_id = d.order_id
GROUP BY o.date;

--calculate the total revenue generated on each day:
SELECT o.date, SUM(d.quantity*p.price) AS perday_revenue
FROM orders o
JOIN order_details d ON o.order_id = d.order_id
JOIN pizzas p ON p.pizza_id = d.pizza_id
GROUP BY o.date;

--what is the total revenue geneated in each month:
SELECT EXTRACT(MONTH FROM o.date) AS month, SUM(d.quantity*p.price) AS monthly_revenue
FROM orders o
JOIN order_details d ON o.order_id = d.order_id
JOIN pizzas p ON p.pizza_id = d.pizza_id
GROUP BY EXTRACT(MONTH FROM o.date)
ORDER BY month;

--Find the top 5 best selling pizza types based on total revenue generated:
SELECT t.name, SUM(d.quantity*p.price) AS revenue
FROM pizza_types t
JOIN pizzas p ON p.pizza_type_id = t.pizza_type_id
JOIN order_details d ON d.pizza_id = p.pizza_id
GROUP BY t.name
ORDER BY t.name DESC LIMIT 5;

-- Find the top 5 pizza category based on total revenue generated:
SELECT t.category, SUM(d.quantity*p.price) AS revenue
FROM pizza_types t
JOIN pizzas p ON p.pizza_type_id = t.pizza_type_id
JOIN order_details d ON d.pizza_id = p.pizza_id
GROUP BY t.category
ORDER BY t.category DESC LIMIT 5;

--At which hour of the day do we receive the heighest number of orders:
SELECT EXTRACT(HOUR FROM time) AS hour, COUNT(order_id) AS total_orders
FROM orders
GROUP BY hour
ORDER BY total_orders DESC LIMIT 1;

--At which hour of the day is the heighest revenue generated:
SELECT EXTRACT(HOUR FROM o.time) AS hour, SUM(d.quantity*p.price) AS revenue_perhr
FROM orders o
JOIN order_details d ON o.order_id = d.order_id
JOIN pizzas p ON p.pizza_id = d.pizza_id
GROUP BY hour
ORDER BY revenue_perhr DESC LIMIT 1;

--What is the average revenue generated per order:
SELECT AVG(order_revenue) AS AOV 
FROM(SELECT o.order_id, SUM(d.quantity*p.price) AS order_revenue 
FROM orders o
JOIN order_details d ON o.order_id = d.order_id
JOIN pizzas p ON p.pizza_id = d.pizza_id
GROUP BY o.order_id) AS order_summary;

--which day of the week receives the heighest no. of orders:
SELECT EXTRACT (DOW FROM date) AS daysof_week, COUNT(order_id) AS total_orders
FROM orders
GROUP BY daysof_week 
ORDER BY total_orders DESC LIMIT 1;

--Which pizza size has the highest number of pizza sold:
SELECT p.size, SUM(d.quantity) AS total_quantity
FROM pizzas p
JOIN order_details d ON p.pizza_id = d.pizza_id
GROUP BY p.size
ORDER BY total_quantity DESC LIMIT 1;

--Which pizza size generates the highest total revenue:
SELECT p.size, SUM(d.quantity*p.price) AS revenue
FROM pizzas p
JOIN order_details d ON p.pizza_id = d.pizza_id
GROUP BY p.size
ORDER BY revenue DESC LIMIT 1;

--rank all pizza types based on their total revenue, from highest to lowest:
WITH pizza_rev AS (
SELECT t.name AS pizza_name, SUM(d.quantity*p.price) AS total_rev
FROM pizzas p
JOIN order_details d ON p.pizza_id = d.pizza_id
JOIN pizza_types t ON t.pizza_type_id = p.pizza_type_id
GROUP BY t.name)
SELECT pizza_name, total_rev, RANK() OVER(
ORDER BY total_rev DESC) AS pizza_rank
FROM pizza_rev;

--rank pizza categories based on therir total revenue:
WITH pizza_reven AS (
SELECT t.category AS pizza_cat, SUM(d.quantity*p.price) AS total_rev
FROM pizzas p
JOIN order_details d ON p.pizza_id = d.pizza_id
JOIN pizza_types t ON t.pizza_type_id = p.pizza_type_id
GROUP BY t.category)
SELECT pizza_cat, total_rev, RANK() OVER(
ORDER BY total_rev DESC) AS category_rank
FROM pizza_reven;

--within each pizza category, rank pizza types by total revenue from highest to lowest:
WITH p_rev AS (
SELECT t.name AS pizza_name, t.category AS pizza_cat, SUM(d.quantity*p.price) AS total_rev
FROM pizzas p
JOIN order_details d ON p.pizza_id = d.pizza_id
JOIN pizza_types t ON t.pizza_type_id = p.pizza_type_id
GROUP BY t.name, t.category)
SELECT pizza_name, pizza_cat, total_rev, RANK() OVER (PARTITION BY pizza_cat
ORDER BY total_rev DESC) AS p_rank
FROM p_rev;

--calculate monthly revenue and show how revenue accumulates month by month throughout the year:
WITH m_rev AS (
SELECT EXTRACT (YEAR FROM o.date) AS year, EXTRACT (MONTH FROM o.date) AS month, SUM(d.quantity*p.price) AS tot_rev
FROM orders o
JOIN order_details d ON o.order_id = d.order_id
JOIN pizzas p ON p.pizza_id = d.pizza_id
GROUP BY month, year)
SELECT month, year, tot_rev, SUM(tot_rev) OVER(
ORDER BY month, year) AS cumulative_rev
FROM m_rev;

--calculate the revenue growth or decline compared to the previous month:
WITH m_rev AS (
SELECT EXTRACT (YEAR FROM o.date) AS year, EXTRACT (MONTH FROM o.date) AS month, SUM(d.quantity*p.price) AS tot_rev
FROM orders o
JOIN order_details d ON o.order_id = d.order_id
JOIN pizzas p ON p.pizza_id = d.pizza_id
GROUP BY year, month)
SELECT month, year, tot_rev,
LAG(tot_rev) OVER(
ORDER BY year, month) AS pre_m_rev, 
tot_rev-LAG(tot_rev) OVER(
ORDER BY year, month) AS rev_diff
FROM m_rev;

--calculate the month-over-revenue growth percentage for each month:
WITH m_rev AS (
SELECT EXTRACT (YEAR FROM o.date) AS year, EXTRACT (MONTH FROM o.date) AS month, SUM(d.quantity*p.price) AS tot_rev
FROM orders o
JOIN order_details d ON o.order_id = d.order_id
JOIN pizzas p ON p.pizza_id = d.pizza_id
GROUP BY year, month)
SELECT month, year, tot_rev,
LAG(tot_rev) OVER(
ORDER BY year, month) AS pre_m_rev, 
ROUND(
(tot_rev-LAG(tot_rev) OVER(
ORDER BY year, month)
)*100
/
NULLIF(
LAG(tot_rev) OVER(
ORDER BY year,month),0),2) AS grow_per
FROM m_rev
ORDER BY year,month;
